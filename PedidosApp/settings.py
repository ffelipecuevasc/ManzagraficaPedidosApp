# Database
# https://docs.djangoproject.com/en/6.0/ref/settings/#databases

# CONFIGURACIÓN DE BASE DE DATOS
# ------------------------------------------------------
# 1. Configuración local: MySQL 8.0 en Docker (compose.yaml). Los datos de conexión
#    vienen de las variables DB_* del .env; la contraseña no tiene valor por defecto.
DATABASE_URL = os.environ.get('DATABASE_URL')
if not DATABASE_URL:
    DB_PASSWORD = os.getenv('DB_PASSWORD')
    if not DB_PASSWORD:
        raise ImproperlyConfigured(
            'Falta la contraseña de la base de datos: define DB_PASSWORD en el archivo .env '
            '(ver .env.example) o define DATABASE_URL.'
        )
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': os.getenv('DB_NAME') or 'manzagrafica_local',
            'USER': os.getenv('DB_USER') or 'root',
            'PASSWORD': DB_PASSWORD,
            'HOST': os.getenv('DB_HOST') or '127.0.0.1',
            'PORT': os.getenv('DB_PORT') or '3306',
        }
    }

# CONFIGURACIÓN DE BASE DE DATOS
# ------------------------------------------------------
# 2. Configuración Producción (PythonAnywhere)
# Si existe la variable DATABASE_URL en el entorno (solo en la nube), se usa esa configuración.
if DATABASE_URL:
    DATABASES = {}
    DATABASES['default'] = dj_database_url.config(
        default=DATABASE_URL,
        conn_max_age=60,
        ssl_require=False
    )

# 3. Base de pruebas (iteración 02-01, RDA-006). Nombre fijo para que no dependa de DB_NAME;
#    juego de caracteres y colación de la línea base de producción (00-01). Django destruye
#    esta base al terminar las pruebas: nunca puede llamarse como una base real.
TEST_DB_NAME = 'test_manzagrafica'
BASES_REALES = {'manzagrafica_local', 'manzagrafica_replica', DATABASES['default'].get('NAME')}
if TEST_DB_NAME in BASES_REALES:
    raise ImproperlyConfigured(
        f'La base de pruebas no puede llamarse {TEST_DB_NAME!r}: coincide con una base real.'
    )
DATABASES['default']['TEST'] = {
    'NAME': TEST_DB_NAME,
    'CHARSET': 'utf8mb4',
    'COLLATION': 'utf8mb4_unicode_ci',
}


